#ifndef MICROFLOW_RP2040_REGS_H
#define MICROFLOW_RP2040_REGS_H

#include <stdint.h>

/* Peripheral base addresses */
#define RP2040_RESETS_BASE   0x4000C000U
#define RP2040_CLOCKS_BASE   0x40008000U
#define RP2040_XOSC_BASE     0x40024000U
#define RP2040_IO_BANK0_BASE 0x40014000U
#define RP2040_SIO_BASE      0xD0000000U

/* Register access */
#define RP2040_REG32(address) (*(volatile uint32_t *)(uintptr_t)(address))

/* Reset registers */
#define RP2040_RESETS_RESET RP2040_REG32(RP2040_RESETS_BASE + 0x00U)
#define RP2040_RESETS_DONE  RP2040_REG32(RP2040_RESETS_BASE + 0x08U)

/* XOSC registers */
#define RP2040_XOSC_CTRL    RP2040_REG32(RP2040_XOSC_BASE + 0x00U)
#define RP2040_XOSC_STATUS  RP2040_REG32(RP2040_XOSC_BASE + 0x04U)
#define RP2040_XOSC_STARTUP RP2040_REG32(RP2040_XOSC_BASE + 0x0CU)

/* Clock registers */
#define RP2040_CLK_REF_CTRL     RP2040_REG32(RP2040_CLOCKS_BASE + 0x30U)
#define RP2040_CLK_REF_SELECTED RP2040_REG32(RP2040_CLOCKS_BASE + 0x38U)

/* SIO GPIO registers */
#define RP2040_SIO_GPIO_OUT_SET RP2040_REG32(RP2040_SIO_BASE + 0x14U)
#define RP2040_SIO_GPIO_OUT_CLR RP2040_REG32(RP2040_SIO_BASE + 0x18U)
#define RP2040_SIO_GPIO_OE_SET  RP2040_REG32(RP2040_SIO_BASE + 0x24U)

/* GPIO configuration */
#define RP2040_IO_FUNC_SIO 5U

#define RP2040_GPIO_CTRL(pin) \
    RP2040_REG32(RP2040_IO_BANK0_BASE + 0x04U + ((pin) * 8U))

/* Reset bits */
#define RP2040_RESET_IO_BANK0   (1U << 5U)
#define RP2040_RESET_PADS_BANK0 (1U << 8U)
#define RP2040_RESET_TIMER      (1U << 21U)


/* XOSC configuration */
#define RP2040_XOSC_FREQUENCY_HZ     12000000U
#define RP2040_XOSC_STARTUP_DELAY_MS 1U

#define RP2040_XOSC_ENABLE        (0xFABU << 12U)
#define RP2040_XOSC_FREQ_1_15_MHZ 0xAA0U
#define RP2040_XOSC_STABLE        (1U << 31U)
#define RP2040_XOSC_STARTUP_COUNT ((RP2040_XOSC_FREQUENCY_HZ * RP2040_XOSC_STARTUP_DELAY_MS + 255999U) / 256000U)


/* Hardware timer */
#define RP2040_TIMER_BASE     0x40054000U
#define RP2040_TIMER_TIMERAWL RP2040_REG32(RP2040_TIMER_BASE + 0x28U)

/* Time conversion */
#define RP2040_MICROSECONDS_PER_MILLISECOND 1000U

/* GPIO */
#define RP2040_GPIO_COUNT 30U

/* Reference clock */
#define RP2040_CLK_REF_SRC_XOSC      2U
#define RP2040_CLK_REF_SELECTED_XOSC (1U << 2U)

#endif /* MICROFLOW_RP2040_REGS_H */
