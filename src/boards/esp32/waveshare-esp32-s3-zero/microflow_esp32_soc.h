#ifndef MICROFLOW_ESP32_SOC_H
#define MICROFLOW_ESP32_SOC_H

#include <stdint.h>

#define MICROFLOW_ESP32_GPIO_BASE 0x60004000U
#define MICROFLOW_ESP32_IOMUX_BASE 0x60009000U
#define MICROFLOW_ESP32_GPIO_OUTPUT_SIGNAL 256U
#define MICROFLOW_ESP32_CPU_MHZ 240U
#define MICROFLOW_ESP32_WS2812_ONE_HIGH_CYCLES 78U
#define MICROFLOW_ESP32_WS2812_ONE_LOW_CYCLES 36U
#define MICROFLOW_ESP32_WS2812_ZERO_HIGH_CYCLES 30U
#define MICROFLOW_ESP32_WS2812_ZERO_LOW_CYCLES 84U

static inline uint32_t microflow_esp32_iomux_offset(uint32_t pin) {
  return 0x04U + (pin * 4U);
}

#define MICROFLOW_ESP32_IOMUX_OFFSET(pin) microflow_esp32_iomux_offset(pin)

#endif
