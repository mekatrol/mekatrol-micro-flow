#ifndef MICROFLOW_ESP32_SOC_H
#define MICROFLOW_ESP32_SOC_H

#include <stdint.h>

#define MICROFLOW_ESP32_GPIO_BASE 0x60091000U
#define MICROFLOW_ESP32_IOMUX_BASE 0x60090000U
#define MICROFLOW_ESP32_GPIO_OUTPUT_SIGNAL 128U
#define MICROFLOW_ESP32_CPU_MHZ 160U
#define MICROFLOW_ESP32_WS2812_ONE_HIGH_CYCLES 52U
#define MICROFLOW_ESP32_WS2812_ONE_LOW_CYCLES 24U
#define MICROFLOW_ESP32_WS2812_ZERO_HIGH_CYCLES 20U
#define MICROFLOW_ESP32_WS2812_ZERO_LOW_CYCLES 56U

static inline uint32_t microflow_esp32_iomux_offset(uint32_t pin) {
  return 0x04U + (pin * 4U);
}

#define MICROFLOW_ESP32_IOMUX_OFFSET(pin) microflow_esp32_iomux_offset(pin)

#endif
